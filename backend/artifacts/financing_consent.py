"""The DEMO "Financing request and assignment consent" document.

Architecture_v4 section 7.1 asks for a document that is obviously **not** a real
instrument: watermarked TEMPLATE, every party fictional, no official styling, and an
explicit statement that the actual terms are set by the platform.

This is deliberately **not** a member of `ArtifactKind`. That enum is part of the
frozen v1.0 contract (`contracts/openapi.json`), and adding a member would change a
v1.0 component. The consent is an internal document attached to a financing track,
not one of the five escalation artifacts.
"""

from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal

from backend.artifacts.common import inr, md_table, pct

WATERMARK = "TEMPLATE"

_BANNER = (
    "**DEMO TEMPLATE — SIMULATED SIGNATURE, NO LEGAL EFFECT.**\n\n"
    "This document is generated by SamadhaanOS for a hackathon demonstration. It is not "
    "issued by any financier, bank, platform or authority. Every party, rate and amount "
    "below is synthetic. The actual terms of any financing are set by the platform used "
    "and by the financier's own documents."
)


@dataclass(frozen=True)
class ConsentInputs:
    """Everything the template prints. No computation happens here."""

    case_id: str
    invoice_no: str
    supplier_name: str
    buyer_name: str
    financier_alias: str
    accepted_amount: Decimal
    annual_rate: Decimal
    discount: Decimal
    fee: Decimal
    net_amount: Decimal
    tenor_days: int
    due_date: str
    bid_id: str
    esign_session_id: str


def build_consent_markdown(inputs: ConsentInputs) -> str:
    """The markdown the PDF is rendered from. Deterministic: same inputs, same bytes."""
    parties = md_table(
        ["Role", "Party"],
        [
            ["Supplier (assignor)", f"{inputs.supplier_name} (synthetic)"],
            ["Buyer", f"{inputs.buyer_name} (synthetic)"],
            ["Financier", f"{inputs.financier_alias} (fictional)"],
        ],
    )
    money = md_table(
        ["Line", "Amount"],
        [
            ["Accepted amount", inr(inputs.accepted_amount)],
            ["Discount at the selected rate", f"- {inr(inputs.discount)}"],
            ["Platform fee", f"- {inr(inputs.fee)}"],
            ["**You receive**", f"**{inr(inputs.net_amount)}**"],
        ],
    )
    terms = md_table(
        ["Term", "Value"],
        [
            ["Invoice", inputs.invoice_no],
            ["Tenor", f"{inputs.tenor_days} day(s)"],
            ["Buyer due date", inputs.due_date],
            ["Financier rate", f"{pct(inputs.annual_rate)} per year"],
            ["Bid reference", inputs.bid_id],
            ["Signing session", inputs.esign_session_id],
        ],
    )

    return "\n\n".join(
        [
            "# Financing request and assignment consent (DEMO TEMPLATE)",
            _BANNER,
            "## Parties",
            parties,
            "## Amounts",
            money,
            "## Terms",
            terms,
            "## Consent",
            (
                "The supplier requests financing of the invoice above and consents to the "
                "assignment of the receivable to the financier named above, **without "
                "recourse to the supplier**, per the platform's terms. This build asserts "
                "nothing about whether a financier can enforce MSMED Act rights; that "
                "question is open (OQ-10) and is never claimed here or in the product."
            ),
            "## Signature",
            (
                "Signed with the **DEMO eSign** simulation. No Aadhaar number is collected, "
                "stored or logged. The signature on this template has no legal effect."
            ),
            "---",
            f"Template generated for {inputs.case_id}. Not a real financing document.",
        ]
    )
