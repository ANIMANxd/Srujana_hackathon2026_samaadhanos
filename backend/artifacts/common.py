def inr(value: Decimal | str) -> str:
    """Format a money figure as rupees with Indian digit grouping.

    The value is printed, never recomputed: it arrives from the engine as a
    Decimal (or its decimal string) already rounded to 0.01, and this helper
    only pads a missing fraction so the column reads as money. No float is
    accepted - a float would be a second, silent rounding of a legal figure.
    """
    if isinstance(value, float):  # pragma: no cover - defensive, golden rule 3
        raise TypeError("money must be Decimal or a decimal string, never float")
    amount = value if isinstance(value, Decimal) else Decimal(str(value))
    sign = "-" if amount < 0 else ""
    whole, _, fraction = format(amount, "f").partition(".")
    fraction = (fraction + "00")[: max(2, len(fraction))]
    return f"{sign}\u20b9{_group_indian(whole.lstrip('-'))}.{fraction}"


def _group_indian(whole: str) -> str:
    """1250000 -> '12,50,000' (lakh/crore grouping, as Indian amounts are read)."""
    if len(whole) <= 3:
        return whole
    head, tail = whole[:-3], whole[-3:]
    parts = [tail]
    while len(head) > 2:
        parts.append(head[-2:])
        head = head[:-2]
    if head:
        parts.append(head)
    return ",".join(reversed(parts))


def pct(value: Decimal | str) -> str:
    """A percentage as the engine printed it, with its sign. No rounding here."""
    return f"{value}%"


def draft_banner(*, case_id: str, calculation_date) -> str:
    """The label every artifact carries at the top (golden rule 9/10)."""
    return (
        "> **DRAFT** \u2014 prepared in SamadhaanOS from your case inputs and your case's "
        "own calculation.\n"
        "> Nothing is sent from here: review it, edit it and approve it before you use it.\n"
        f"> Case {case_id} \u00b7 figures as on {calculation_date.isoformat()}"
    )


def closing_footer(*, case_id: str, calculation_date) -> str:
    """The not-legal-advice footer every artifact ends with."""
    return (
        "\n---\n\n"
        "*Not legal advice. This draft was generated by SamadhaanOS from the data "
        f"entered for {case_id} and the figures the engine returned as on "
        f"{calculation_date.isoformat()}. It is decision support, not a lawyer's "
        "opinion, not a filing, and not a government form. Nothing is sent "
        "automatically: the owner reviews, edits and approves every draft.*"
    )


def bullets(items: Sequence[str]) -> str:
    """A markdown bullet list; blank input renders nothing."""
    if not items:
        return ""
    return "\n".join(f"- {item}" for item in items)


def assumptions_section(items: Sequence[str]) -> str:
    """The assumptions block that closes every artifact."""
    return "## Assumptions this draft was made under\n\n" + bullets(items) + "\n"


def open_points_section(warnings: Sequence[Warning]) -> str:
    """The engine's open points, shown rather than hidden (principle 6).

    Empty input renders nothing: a case with no open points gains no empty
    heading.
    """
    if not warnings:
        return ""
    lines = [f"- {w.text}" for w in warnings]
    return "## Open points from this calculation\n\n" + "\n".join(lines) + "\n"


def md_cell(value) -> str:
    """Escape one table cell so engine text with a pipe or a newline still fits."""
    text = " ".join(str(value).split())
    return text.replace("|", "\\|")


def md_table(headers: Sequence[str], rows: Sequence[Sequence]) -> str:
    """A GitHub-flavoured markdown table. No row is computed, only printed."""
    if not rows:
        return ""
    head = "| " + " | ".join(md_cell(h) for h in headers) + " |"
    rule = "|" + "|".join(" --- " for _ in headers) + "|"
    body = "\n".join(
        "| " + " | ".join(md_cell(cell) for cell in row) + " |" for row in rows
    )
    return "\n".join((head, rule, body))


def join_blocks(*blocks: str) -> str:
    """Join the non-empty parts of a document with one blank line between them."""
    return "\n\n".join(
        block.strip("\n") for block in blocks if block and block.strip("\n")
    )
