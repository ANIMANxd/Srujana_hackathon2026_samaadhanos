"""Drafting furniture shared by every SamadhaanOS artifact.

An artifact is a template: it prints figures the engine already produced and
strings the request already carries, and it computes nothing (AGENTS.md golden
rules 6 and 7). What lives here is the furniture that wraps every draft - the
DRAFT banner, the assumptions block, the open-points block, the not-legal-advice
footer - plus the two formatters the documents need.

No clock is read anywhere in `backend/artifacts`: a draft is stamped with the
case's own calculation date, so the same request always produces the same text.
"""

from decimal import Decimal
from typing import Sequence

from backend.app.schemas import Warning

# Plain-English label for an evidence kind, mirroring the frontend dictionary
