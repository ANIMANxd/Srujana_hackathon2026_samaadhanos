"""Generate contracts/types.ts from contracts/openapi.json (section 9.1).

Run: python -m backend.app.export_types   (or `make types`)

Primary path shells out to `npx openapi-typescript` when Node is available,
because the frontend expects its familiar `components["schemas"]` / `paths` /
`operations` shapes. When Node/npx is missing (offline laptop, demo machine),
a small deterministic generator emits the same shapes so the build never
depends on the network (principle 5, offline-first).

The committed types.ts is produced by the primary path. The fallback exists so
`make types` still works without Node; both write equivalent interfaces.
"""

import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OPENAPI = ROOT / "contracts" / "openapi.json"
TYPES = ROOT / "contracts" / "types.ts"


def generate_with_openapi_typescript() -> bool:
    """Return True on success, False if npx/node is unavailable."""
    npx = shutil.which("npx") or shutil.which("npx.cmd")
    if not npx:
        return False
    try:
        subprocess.run(
            [npx, "--yes", "openapi-typescript@latest", str(OPENAPI), "-o", str(TYPES)],
            check=True,
            cwd=ROOT,
            capture_output=True,
        )
        return True
    except (subprocess.CalledProcessError, OSError):
        return False


def _ts_type(schema: dict, spec: dict) -> str:
    """Translate a JSON-schema fragment into a TypeScript type string."""
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    t = schema.get("type")
    if t == "null":
        return "null"
    if t == "string":
        return "string"
    if t == "integer" or t == "number":
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "array":
        inner = _ts_type(schema.get("items", {}), spec)
        return f"({inner})[]" if " " in inner else f"{inner}[]"
    if t == "object" or "properties" in schema:
        props = schema.get("properties", {})
        required = set(schema.get("required", []))
        if not props:
            return "Record<string, never>"
        lines = []
        for name, sub in props.items():
            opt = "" if name in required else "?"
            lines.append(f"        {name}{opt}: {_ts_type(sub, spec)};")
        return "{\n" + "\n".join(lines) + "\n    }"
    if "anyOf" in schema:
        parts = [_ts_type(s, spec) for s in schema["anyOf"]]
        return " | ".join(dict.fromkeys(parts))
    return "unknown"


def _is_enum(schema: dict) -> bool:
    return "enum" in schema and schema.get("type") == "string"


def generate_builtin() -> None:
    spec = json.loads(OPENAPI.read_text(encoding="utf-8"))
    out = [
        "/**",
        " * Generated by backend/app/export_types.py (offline fallback generator).",
        " * Do not edit by hand. Regenerate with `make types`.",
        " *",
        " * Equivalent shapes to openapi-typescript output.",
        " */",
        "",
    ]
    schemas = spec.get("components", {}).get("schemas", {})
    for name in sorted(schemas):
        schema = schemas[name]
        if _is_enum(schema):
            out.append(f"export type {name} = {_ts_type(schema, spec)};")
        else:
            out.append(f"export interface {name} " + _ts_type(schema, spec))
        out.append("")
    TYPES.write_text("\n".join(out), encoding="utf-8")


def main() -> int:
    if not OPENAPI.is_file():
        print(f"missing {OPENAPI}; run `make openapi` first", file=sys.stderr)
        return 1
    if generate_with_openapi_typescript():
        print(f"wrote {TYPES} (openapi-typescript)")
    else:
        generate_builtin()
        print(f"wrote {TYPES} (built-in fallback; install Node for openapi-typescript)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
