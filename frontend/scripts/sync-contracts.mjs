// Copies the frozen contract into the frontend so Next/Turbopack can resolve it.
//
// Turbopack does not resolve files outside the project root, so instead of
// importing ../contracts directly we copy, on every install/dev/build:
//   ../contracts/types.ts           -> generated/contract-types.ts
//   ../contracts/fixtures/*.json    -> fixtures/*.json (+ fixtures/index.ts)
//   ../contracts/fixtures/*.md      -> artifact samples, inlined in fixtures/index.ts
//   ../contracts/fixtures/v4/*.json -> fixtures/v4/*.json (contract v1.1 offline samples,
//                                      exported as RAW_V4 keyed by file name)
//   ../backend/presets/*.json       -> preset titles only (read, never written)
//   ../backend/extraction/demo/*.txt + cache/*.json
//                                   -> synthetic upload samples and the results the
//                                      extractor generated for them (offline demo)
// Both output folders are git-ignored: the contract stays the single source of
// truth and a `git pull` of backend changes is picked up on the next run.
// This script only READS outside frontend/.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const frontend = path.resolve(here, "..");
const repo = path.resolve(frontend, "..");
const contractsDir = path.join(repo, "contracts");
const fixturesSrc = path.join(contractsDir, "fixtures");
const presetsSrc = path.join(repo, "backend", "presets");
const extractionDemoSrc = path.join(repo, "backend", "extraction", "demo");
const extractionCacheSrc = path.join(repo, "backend", "extraction", "cache");
const generatedDir = path.join(frontend, "generated");
const fixturesOut = path.join(frontend, "fixtures");

const HEADER = "// GENERATED by scripts/sync-contracts.mjs. Do not edit; edit ../contracts instead.\n";

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch {
    return null;
  }
}

fs.mkdirSync(generatedDir, { recursive: true });
fs.rmSync(fixturesOut, { recursive: true, force: true });
fs.mkdirSync(fixturesOut, { recursive: true });

// 1. Types
const typesSrc = path.join(contractsDir, "types.ts");
if (!fs.existsSync(typesSrc)) {
  console.error(`[sync-contracts] missing ${typesSrc}; run \`make types\` in the repo root.`);
  process.exit(1);
}
fs.writeFileSync(path.join(generatedDir, "contract-types.ts"), HEADER + fs.readFileSync(typesSrc, "utf8"));

// 2. Fixtures, paired by preset id
const files = fs.existsSync(fixturesSrc) ? fs.readdirSync(fixturesSrc).filter((f) => f.endsWith(".json")) : [];
for (const f of files) fs.copyFileSync(path.join(fixturesSrc, f), path.join(fixturesOut, f));

const ids = [...new Set(files.map((f) => f.replace(/\.(request|response)\.json$/, "")))]
  .filter((id) => files.includes(`${id}.request.json`))
  .sort();

const lines = [HEADER];
const entries = [];
ids.forEach((id, i) => {
  const hasResponse = files.includes(`${id}.response.json`);
  lines.push(`import req${i} from "./${id}.request.json";`);
  if (hasResponse) lines.push(`import res${i} from "./${id}.response.json";`);
  const preset = readJson(path.join(presetsSrc, `${id}.json`));
  const title = preset && typeof preset.title === "string" ? preset.title : id;
  entries.push(
    `  { id: ${JSON.stringify(id)}, title: ${JSON.stringify(title)}, request: req${i} as unknown, response: ${
      hasResponse ? `res${i} as unknown` : "null"
    } },`,
  );
});
lines.push("");
lines.push("export type RawFixture = { id: string; title: string; request: unknown; response: unknown | null };");
lines.push("");
lines.push("export const RAW_FIXTURES: RawFixture[] = [");
lines.push(...entries);
lines.push("];");

// 3. Artifact samples: <case>.<KIND>.md, engine-generated drafts
const mdFiles = fs.existsSync(fixturesSrc) ? fs.readdirSync(fixturesSrc).filter((f) => /^.+\.[A-Z0-9_]+\.md$/.test(f)).sort() : [];
const artifacts = mdFiles.map((f) => {
  const [, id, kind] = f.match(/^(.+)\.([A-Z0-9_]+)\.md$/);
  return { id, kind, markdown: fs.readFileSync(path.join(fixturesSrc, f), "utf8") };
});
lines.push("");
lines.push("export type RawArtifact = { id: string; kind: string; markdown: string };");
lines.push("");
lines.push(`export const RAW_ARTIFACTS: RawArtifact[] = ${JSON.stringify(artifacts, null, 2)};`);

// 4. Extraction samples: the synthetic text plus what the extractor produced for it
const samples = [];
const cacheFiles = fs.existsSync(extractionCacheSrc) ? fs.readdirSync(extractionCacheSrc).filter((f) => f.endsWith(".json")) : [];
for (const f of cacheFiles) {
  const cached = readJson(path.join(extractionCacheSrc, f));
  const name = cached && typeof cached.generated_from === "string" ? cached.generated_from : null;
  if (!name || !cached.response) continue;
  const textFile = path.join(extractionDemoSrc, name);
  if (!fs.existsSync(textFile)) continue;
  samples.push({ name, text: fs.readFileSync(textFile, "utf8"), response: cached.response });
}
samples.sort((a, b) => a.name.localeCompare(b.name));
lines.push("");
lines.push("export type RawExtractionSample = { name: string; text: string; response: unknown };");
lines.push("");
lines.push(`export const RAW_EXTRACTION_SAMPLES: RawExtractionSample[] = ${JSON.stringify(samples, null, 2)};`);

// 5. Contract v1.1 samples: each file is {_fixture, payload}; keyed by file name without .json
const v4Src = path.join(fixturesSrc, "v4");
const v4Files = fs.existsSync(v4Src)
  ? fs.readdirSync(v4Src).filter((f) => f.endsWith(".json") && f !== "v1-contract-baseline.json").sort()
  : [];
fs.mkdirSync(path.join(fixturesOut, "v4"), { recursive: true });
v4Files.forEach((f, i) => {
  fs.copyFileSync(path.join(v4Src, f), path.join(fixturesOut, "v4", f));
  lines.push(`import v4_${i} from "./v4/${f}";`);
});
lines.push("");
lines.push("export const RAW_V4: Record<string, unknown> = {");
v4Files.forEach((f, i) => lines.push(`  ${JSON.stringify(f.replace(/\.json$/, ""))}: v4_${i} as unknown,`));
lines.push("};");

// 6. Contract v1.2 samples (customer book): same {_fixture, payload} shape, exported as RAW_V5
const v5Src = path.join(fixturesSrc, "v5");
const v5Files = fs.existsSync(v5Src)
  ? fs.readdirSync(v5Src).filter((f) => f.endsWith(".json") && !f.includes("contract-baseline")).sort()
  : [];
fs.mkdirSync(path.join(fixturesOut, "v5"), { recursive: true });
v5Files.forEach((f, i) => {
  fs.copyFileSync(path.join(v5Src, f), path.join(fixturesOut, "v5", f));
  lines.push(`import v5_${i} from "./v5/${f}";`);
});
lines.push("");
lines.push("export const RAW_V5: Record<string, unknown> = {");
v5Files.forEach((f, i) => lines.push(`  ${JSON.stringify(f.replace(/\.json$/, ""))}: v5_${i} as unknown,`));
lines.push("};");

fs.writeFileSync(path.join(fixturesOut, "index.ts"), lines.join("\n") + "\n");

console.log(
  `[sync-contracts] types + ${ids.length} fixture case(s): ${ids.join(", ") || "none"}; ` +
    `${artifacts.length} artifact sample(s); ${samples.length} extraction sample(s); ${v4Files.length} v1.1 sample(s); ` +
    `${v5Files.length} v1.2 sample(s)`,
);
